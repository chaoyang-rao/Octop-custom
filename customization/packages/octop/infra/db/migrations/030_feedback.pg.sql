CREATE TABLE IF NOT EXISTS feedback (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  feedback_id TEXT NOT NULL UNIQUE,
  submission_key TEXT NOT NULL,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  author_name TEXT NOT NULL,
  section TEXT NOT NULL,
  kind TEXT NOT NULL CHECK(kind IN ('problem','suggestion','other')),
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  client_version TEXT NOT NULL DEFAULT '',
  client_platform TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'new' CHECK(status IN ('new','in_progress','resolved')),
  reply TEXT NOT NULL DEFAULT '',
  revision INTEGER NOT NULL DEFAULT 1,
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL,
  UNIQUE(user_id, submission_key)
);
CREATE INDEX IF NOT EXISTS idx_feedback_created ON feedback(created_at, id);
CREATE INDEX IF NOT EXISTS idx_feedback_section_status ON feedback(section, status, created_at);
CREATE INDEX IF NOT EXISTS idx_feedback_user ON feedback(user_id, created_at);
UPDATE _schema_version SET version = 30;
