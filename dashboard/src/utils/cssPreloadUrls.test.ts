// @vitest-environment node
import {
  afterAll,
  afterEach,
  beforeAll,
  beforeEach,
  expect,
  it,
  vi,
} from "vitest";
import { build, type Plugin } from "vite";
import { JSDOM } from "jsdom";
import { mkdtemp, realpath, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { cssPreloadUrls } from "../../vite/css-preload-urls";

let directory: string;
let helper = "";
let dom: JSDOM;
let document: Document;
let window: Window;
beforeEach(() => {
  dom = new JSDOM("<!doctype html><head></head><body></body>", {
    url: "http://localhost/",
  });
  document = dom.window.document;
  window = dom.window as unknown as Window;
});

beforeAll(async () => {
  directory = await realpath(
    await mkdtemp(join(tmpdir(), "octop-preload-test-")),
  );
  await writeFile(
    join(directory, "index.html"),
    '<script type="module" src="/main.js"></script>',
  );
  await writeFile(
    join(directory, "main.js"),
    'window.loadPage = () => import("./page.js");',
  );
  await writeFile(
    join(directory, "page.js"),
    'import "./page.css"; export const ready = true;',
  );
  await writeFile(join(directory, "page.css"), ".layout { display: grid; }");
  const capture: Plugin = {
    name: "capture-real-preload-helper",
    enforce: "post",
    transform(code, id) {
      if (id === "\0vite/preload-helper.js") helper = code;
    },
  };
  await build({
    configFile: false,
    root: directory,
    publicDir: false,
    logLevel: "silent",
    plugins: [cssPreloadUrls(), capture],
    build: { write: false, modulePreload: { polyfill: false } },
  });
  expect(helper).toContain("__vitePreload");
});

afterEach(() => {
  dom?.window.close();
});

afterAll(async () => {
  if (directory) await rm(directory, { recursive: true, force: true });
});

function preload() {
  // Execute the helper generated by the installed Vite, not a handwritten loader.
  return new Function(
    "document",
    "window",
    "__VITE_IS_MODERN__",
    helper.replace("export const __vitePreload", "const __vitePreload") +
      "; return __vitePreload;",
  )(document, window, true) as (
    load: () => Promise<string>,
    urls: string[],
  ) => Promise<string>;
}

it.each([
  "assets/preload-style-test.css",
  "assets/preload-style-test.css?turn-space=20261118-chat-top",
  "assets/preload-style-test.css#version",
  "assets/preload-style-test.css?v=2#layout",
])(
  "loads %s as a stylesheet and waits before rendering the page",
  async (url) => {
    const load = vi.fn(async () => "page ready");
    const pending = preload()(load, [url]);
    const link = document.head.querySelector<HTMLLinkElement>(
      'link[href*="preload-style-test"]',
    )!;
    expect(link.rel).toBe("stylesheet");
    expect(link.getAttribute("as")).not.toBe("script");
    await Promise.resolve();
    expect(load).not.toHaveBeenCalled();
    link.dispatchEvent(new dom.window.Event("load"));
    expect(await pending).toBe("page ready");
  },
);

it("keeps JavaScript with a css-looking query as a script preload", async () => {
  const pending = preload()(
    async () => "ready",
    ["assets/preload-style-test.js?style=file.css"],
  );
  const link = document.head.querySelector<HTMLLinkElement>(
    'link[href*="preload-style-test"]',
  )!;
  expect(link.rel).not.toBe("stylesheet");
  expect(link.as).toBe("script");
  expect(await pending).toBe("ready");
});
